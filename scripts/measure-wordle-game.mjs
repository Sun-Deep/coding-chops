import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import "./ts-register.mjs";
import { feedback, remaining } from "../src/vertical/54-wordle/wordle.ts";

const input = readFileSync("scripts/fixtures/wordle/answers.txt", "utf8");
const answers = input.trim().split(/\s+/);
const answer = "trace";
const previous = JSON.parse(
  readFileSync("curriculum/vertical/54-wordle/runs/first.json", "utf8"),
);
const data = {
  answer,
  answerCount: answers.length,
  adieu: remaining(answers, "adieu", answer),
  roate: remaining(answers, "roate", answer),
  feedback: {
    adieu: feedback("adieu", answer),
    roate: feedback("roate", answer),
    solved: feedback(answer, answer),
  },
};
data.steps = Object.fromEntries(
  ["adieu", "roate"].map((word) => [
    word,
    [
      answers.length,
      ...[1, 2, 3, 4, 5].map(
        (length) =>
          answers.filter(
            (candidate) =>
              feedback(word, candidate).slice(0, length).join("") ===
              data.feedback[word].slice(0, length).join(""),
          ).length,
      ),
    ],
  ]),
);
assert(answers.includes(answer));
for (const word of ["adieu", "roate"]) {
  const encoded = data.feedback[word].reduce(
    (sum, digit, i) => sum + digit * 3 ** i,
    0,
  );
  const old = previous.selected.find((row) => row.word === word);
  assert.equal(data[word].length, old.histogram[encoded]);
  assert(data[word].includes(answer));
}
assert.deepEqual(feedback("allee", "apple"), [2, 1, 0, 0, 2]);
assert.deepEqual(data.feedback.roate, [1, 0, 2, 1, 2]);
assert.deepEqual(data.feedback.solved, [2, 2, 2, 2, 2]);
const record = {
  started: new Date().toISOString(),
  answersSha256: createHash("sha256").update(input).digest("hex"),
  checks:
    "Feedback counts match the complete benchmark histograms. Duplicate letters and the winning row checked independently.",
  ...data,
};
writeFileSync(
  "src/vertical/54-wordle/gameplay.ts",
  "// Generated by scripts/measure-wordle-game.mjs. Historical replay, not today's puzzle.\nexport const GAME = " +
    JSON.stringify(data, null, 2) +
    " as const;\n",
);
const { gameAt } = await import("../src/vertical/54-wordle/game.ts");
const beats = await import("../src/vertical/54-wordle/beats.ts");
for (let frame = 0; frame < beats.DURATION; frame++) {
  const state = gameAt(frame);
  assert.equal(state.rows.length, 6);
  for (const row of state.rows) {
    assert.equal(row.length, 5);
    for (const tile of row) {
      assert([-1, 0, 1, 2].includes(tile.status));
      assert(Number.isFinite(tile.angle));
    }
  }
  for (const status of Object.values(state.keyboard))
    assert([0, 1, 2].includes(status));
  assert(state.count >= 1 && state.count <= data.answerCount);
}
assert.equal(gameAt(74).count, data.adieu.length);
assert.equal(gameAt(205).count, data.roate.length);
assert.deepEqual(
  gameAt(205).rows[0].map((tile) => tile.status),
  data.feedback.roate,
);
assert.deepEqual(
  gameAt(beats.WIN).rows[1].map((tile) => tile.status),
  data.feedback.solved,
);
assert.equal(gameAt(beats.WIN).keyboard.R, 2);
assert.equal(gameAt(beats.WIN).keyboard.O, 0);
assert.equal(gameAt(beats.TYPE_B).keyboard.D, undefined);
record.frameChecks = beats.DURATION;
writeFileSync(
  "curriculum/vertical/54-wordle/runs/gameplay.json",
  JSON.stringify(record, null, 2) + "\n",
);
console.log(
  JSON.stringify(
    { ...record, adieu: data.adieu.length, roate: data.roate.length },
    null,
    2,
  ),
);
