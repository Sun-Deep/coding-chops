// Write scene durations from the locked narration stems into a TypeScript file
// the compositions import.
//
// Usage: node scripts/narration-durations.mjs <track>/<episode>
//   e.g. node scripts/narration-durations.mjs system-design/01-single-server
//
// The episode argument used to be hardcoded, which made the script invisible to
// a second track. It derives both the stems directory and the output file, so
// the two can never point at different episodes.
//
// The production standard makes locked narration audio the timing source of
// truth. Remotion runs in a bundle and cannot read the stems itself, so this
// copies their measured lengths into source. Run it after any re-record.
//
// Never hand-edit the generated file. If a number there disagrees with the
// audio, this script is the answer, not the editor.

import { execFileSync } from "node:child_process";
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dirname, "..");
const episode = process.argv[2];

if (!episode || !episode.includes("/")) {
  throw new Error(
    "Pass the episode as <track>/<episode>, " +
      "for example system-design/01-single-server.",
  );
}

const episodeDir = path.join("curriculum", episode);
const stemsDir = path.join(repoRoot, episodeDir, "audio/master");
const outFile = path.join(repoRoot, "src/tracks", episode, "narration.ts");

const duration = (file) =>
  Number(
    execFileSync("ffprobe", [
      "-v",
      "error",
      "-show_entries",
      "format=duration",
      "-of",
      "csv=p=0",
      file,
    ])
      .toString()
      .trim(),
  );

const stems = (await readdir(stemsDir))
  .filter((f) => f.endsWith(".wav"))
  .sort();
const scenes = stems.map((file) => ({
  id: path.basename(file, ".wav"),
  seconds: Number(duration(path.join(stemsDir, file)).toFixed(3)),
}));

const total = scenes.reduce((sum, s) => sum + s.seconds, 0);

const body = `// Generated by scripts/narration-durations.mjs. Do not edit by hand.
//
// Every number here is measured from a locked narration stem in
// ${episodeDir}/audio/master. Re-run the script after a re-record.

export const narration = [
${scenes.map((s) => `  { id: "${s.id}", seconds: ${s.seconds}, audio: "${s.id}.wav" },`).join("\n")}
] as const;

export type NarrationScene = (typeof narration)[number]["id"];

/** Total runtime with no gaps between scenes: ${Math.floor(total / 60)}:${String(Math.floor(total % 60)).padStart(2, "0")}. */
export const narrationSeconds = ${Number(total.toFixed(3))};
`;

await writeFile(outFile, body);
console.log(
  `${scenes.length} scenes, ${total.toFixed(1)}s -> ${path.relative(repoRoot, outFile)}`,
);
